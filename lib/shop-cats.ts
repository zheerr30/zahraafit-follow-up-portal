/** Which section an item goes in. */
export function sectionOf(name: string): ShopSection {
  for (const [sec, re] of RULES) if (re.test(name)) return sec;
  return "أخرى";
}

/** "حبة" and "حبات" are the same unit; grams and ml stay apart. */
export function unitKey(u: string) {
  const x = (u || "").trim();
  if (/^(غ|جم|جرام|غرام|g)$/i.test(x)) return "غ";
  if (/^(مل|ml)$/i.test(x)) return "مل";
  if (/^حب/.test(x)) return "حبة";
  if (/^شر/.test(x)) return "شريحة";
  if (/^ملع/.test(x)) return "ملعقة";
  if (/^كو/.test(x)) return "كوب";
  return x;
}

/** How the summed amount reads: "5 حبات", "1 حبة", "800 غ". */
export function amountText(n: number, u: string) {
  const v = Math.round(n * 10) / 10;
  const k = unitKey(u);
  const unit = k === "حبة" ? (v > 2 && v <= 10 ? "حبات" : "حبة") : k === "شريحة" ? (v > 2 && v <= 10 ? "شرائح" : "شريحة") : u;
  return `${v} ${unit}`.trim();
}

/** Same name, ignoring spaces and «نيء». */
export const nameKey = (n: string) => n.replace(/\(.*?\)/g, "").replace(/\s+(نيء|نية|طازج|طازجة)$/, "").replace(/\s+/g, " ").trim();
